const MONTHS = [
  'january', 'february', 'march', 'april', 'may', 'june',
  'july', 'august', 'september', 'october', 'november', 'december',
];

/** Parses the "Month D, YYYY" strings above without relying on Date parsing quirks. */
export function parseEventDate(dateText) {
  const match = /^([A-Za-z]+)\s+(\d{1,2}),\s*(\d{4})$/.exec(String(dateText || '').trim());
  if (!match) return null;
  const month = MONTHS.indexOf(match[1].toLowerCase());
  if (month === -1) return null;
  return { month: month + 1, day: Number(match[2]), year: Number(match[3]) };
}

export function eventYear(event) {
  return parseEventDate(event?.date)?.year ?? null;
}

/** True when the moment shares a calendar day with `today`. */
export function isAnniversary(event, today = new Date()) {
  const parsed = parseEventDate(event?.date);
  if (!parsed) return false;
  return parsed.month === today.getMonth() + 1 && parsed.day === today.getDate();
}

export function anniversariesFor(today = new Date(), events = HISTORICAL_EVENTS) {
  return events.filter(event => isAnniversary(event, today));
}

